METHODS = [("vector", {"method": "vector"}), ("bm25", {"method": "bm25"}),
           ("fusion (α=0.5)", {"method": "fusion", "alpha": 0.5}), ("rrf", {"method": "rrf"})]
ALPHAS = [0.0, 0.25, 0.5, 0.75, 1.0]
OUT_PATH = Path(__file__).resolve().parent.parent / "docs" / "evaluation" / "rag_retrieval.md"


def first_relevant_rank(retriever: FusionRetriever, query: str, gold: list[str], **kwargs) -> int | None:
    hits = retriever.search(query, k=10, **kwargs)
    return next((rank for rank, hit in enumerate(hits, 1) if hit.source in gold), None)


def summarize(ranks: list[int | None]) -> dict[str, float]:
    n = len(ranks)
    return {"hit@1": sum(r == 1 for r in ranks) / n,
            "hit@5": sum(r is not None and r <= 5 for r in ranks) / n,
            "mrr@10": sum(1 / r for r in ranks if r) / n}


def table(rows: list[tuple[str, dict[str, float]]], first_col: str) -> str:
    out = [f"| {first_col} | hit@1 | hit@5 | MRR@10 |", "|---|---|---|---|"]
    best = {m: max(r[m] for _, r in rows) for m in ("hit@1", "hit@5", "mrr@10")}
    for name, r in rows:
        cells = [f"**{r[m]:.2f}**" if abs(r[m] - best[m]) < 1e-9 else f"{r[m]:.2f}" for m in ("hit@1", "hit@5", "mrr@10")]
        out.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def main() -> None:
    retriever = FusionRetriever()
    ranks: dict[str, list[int | None]] = {name: [] for name, _ in METHODS}
    for _, query, gold in QUESTIONS:
        for name, kwargs in METHODS:
            ranks[name].append(first_relevant_rank(retriever, query, gold, **kwargs))

    sections = []
    for subset in ("all", "keyword", "paraphrase"):
        idx = [i for i, (kind, _, _) in enumerate(QUESTIONS) if subset == "all" or kind == subset]
        rows = [(name, summarize([ranks[name][i] for i in idx])) for name, _ in METHODS]
        sections.append(f"### {subset.capitalize()} questions (n={len(idx)})\n\n" + table(rows, "Method"))

    sweep_rows = []
    for alpha in ALPHAS:
        rs = [first_relevant_rank(retriever, q, g, method="fusion", alpha=alpha) for _, q, g in QUESTIONS]
        label = {0.0: "0.0 (= BM25)", 1.0: "1.0 (= vector)"}.get(alpha, str(alpha))
        sweep_rows.append((label, summarize(rs)))

    detail = ["| # | Type | Question | " + " | ".join(name for name, _ in METHODS) + " |",
              "|---|---|---|" + "---|" * len(METHODS)]
    for i, (kind, query, _) in enumerate(QUESTIONS):
        cells = [str(ranks[name][i]) if ranks[name][i] else "–" for name, _ in METHODS]
        detail.append(f"| {i + 1} | {kind} | {query} | " + " | ".join(cells) + " |")

    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    report = f"""# RAG retrieval evaluation: fusion vs vector vs BM25

Generated by `python -m rag_server.evaluate` on {dt.date.today().isoformat()}.
Corpus: RAGAS docs @ `{manifest['source_commit'][:10]}`: {manifest['documents']} pages, {manifest['chunks']} chunks
({manifest['chunk_size']} chars, {manifest['chunk_overlap']} overlap), embeddings: {manifest['embedding_model']}.

{len(QUESTIONS)} hand-labelled questions. A hit is a retrieved chunk from a page that answers the question.
**Bold** = best in column.

{(chr(10) * 2).join(sections)}

### Fusion weight sweep (all questions)

`fused = α × vector + (1 − α) × BM25`

{table(sweep_rows, "α")}

### Rank of the first relevant chunk per question (– = not in top 10)

{chr(10).join(detail)}
"""
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(report, encoding="utf-8")
    print(report)
    print(f"Written to {OUT_PATH}")


if __name__ == "__main__":
    main()
